#!/usr/bin/env node
// lastfomo build: one source, two publish targets, brand check in the middle.
//   site/  ──►  site/tokens.css (generated from brand/tokens.json)
//          ──►  dist/web/                    full document + files, for any static host (Vercel)
//          ──►  dist/artifact/lastfomo.html  fragment with CSS, JS and images inlined, for a claude.ai Artifact
//          ──►  dist/preview/                the web build with the Hortus shop, while site/shop.json is not live
// Usage: node tools/build.mjs [--no-check]
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { loadShop, withShop } from './shop/render.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const P = (...p) => join(ROOT, ...p);
const read = (p) => readFileSync(P(p), 'utf8');
const args = new Set(process.argv.slice(2));
const fail = (msg) => { console.error('build: ' + msg); process.exit(1); };

/* ---------- 1. tokens.css from brand/tokens.json ---------- */
const T = JSON.parse(read('brand/tokens.json'));
const decl = (obj, prefix = '') => Object.entries(obj).filter(([k]) => !k.startsWith('$')).map(([k, v]) => `--${prefix}${k}:${v}`).join(';');
const WINGS = Object.entries(T.wing).filter(([, w]) => w.signal && T.color[w.name]);
const tokensCss = [
  '/* GENERATED by tools/build.mjs from brand/tokens.json. Do not edit by hand. */',
  '/* Light (Mist) on bare :root; dark (Night) from the viewer or data-theme. Plates stay dark in both. */',
  ':root{',
  '  ' + decl(T.color) + ';',
  '  ' + decl(T.theme.light) + ';',
  '  --wing:var(--fg);--wing-t:var(--fg);--on-wing:var(--bg);',
  '  ' + decl(T.motion) + ';',
  `  --disp:${T.type.display.family};--sans:${T.type.sans.family};--mono:${T.type.mono.family};`,
  '  ' + decl(T.layout) + ';',
  '  color-scheme:light',
  '}',
  `@media (prefers-color-scheme:dark){:root:not([data-theme="light"]){${decl(T.theme.dark)};color-scheme:dark}}`,
  `:root[data-theme="dark"]{${decl(T.theme.dark)};color-scheme:dark}`,
  ...WINGS.map(([key]) => `[data-wing="${key}"]{--wing:var(--${key});--wing-t:var(--${key}-t);--on-wing:var(--ink)}`),
  '',
].join('\n');
writeFileSync(P('site/tokens.css'), tokensCss);

/* ---------- 2. brand check on the source ---------- */
async function brandcheck(opts, label) {
  const mod = P('tools/brandcheck.mjs');
  if (!existsSync(mod)) { console.warn(`build: tools/brandcheck.mjs not found, skipping the ${label} check`); return true; }
  const { check } = await import(pathToFileURL(mod).href);
  const r = await check({ root: ROOT, ...opts });
  for (const w of r.warnings) console.warn(`  warn  ${w.rule} ${w.id}: ${w.message}${w.file ? ` (${w.file}${w.line ? ':' + w.line : ''})` : ''}`);
  for (const e of r.errors) console.error(`  ERROR ${e.rule} ${e.id}: ${e.message}${e.file ? ` (${e.file}${e.line ? ':' + e.line : ''})` : ''}`);
  console.log(`build: ${label} check — ${r.errors.length} errors, ${r.warnings.length} warnings`);
  return r.errors.length === 0;
}
if (!args.has('--no-check') && !(await brandcheck({}, 'source'))) fail('brand check failed on site/. Fix the errors above (or run with --no-check to inspect the output).');

/* ---------- 3. assemble ---------- */
// The Hortus shop renders from site/shop.json at its markers in site/index.html. The Artifact always carries it, for
// the owner to review; the live site only once shop.json says "live": true. Until then dist/preview/ is the web
// build with the shop in place, for QA. It is never deployed: vercel.json serves dist/web.
let shop = null;
try { shop = loadShop(P('site')); } catch (err) { fail(err.message); }
const source = read('site/index.html');
const shopIn = (include) => { try { return withShop(source, shop, include); } catch (err) { return fail(err.message); } };
let html = shopIn(true);
const shopLive = !shop || shop.live === true;
const webSource = shopLive ? html : shopIn(false);
const media = JSON.parse(read('site/media.json'));
const once = (s, re, fn) => { let n = 0; const out = s.replace(re, (...m) => { n++; return fn(...m); }); if (n !== 1) fail(`expected exactly one match for ${re}, found ${n}`); return out; };
const withManifest = (doc, obj) => once(doc, /(<script type="application\/json" id="lf-media">)[\s\S]*?(<\/script>)/, (_, a, b) => a + JSON.stringify(obj).replace(/</g, '\\u003c') + b);

// Films: every play control links to the film named in site/media.json, and nothing else.
const watch = (id) => `https://www.youtube.com/watch?v=${id}`;
for (const m of html.matchAll(/<a\b[^>]*\bdata-play="(\w+)"[^>]*>/g)) {
  const k = m[1], id = media.films?.[k]?.youtube, href = (m[0].match(/href="([^"]*)"/) || [])[1];
  if (!id) fail(`a play control for "${k}" has no film in site/media.json`);
  if (href !== watch(id)) fail(`play control for "${k}" links to ${href}, but site/media.json says ${watch(id)}`);
  if (!/target="_blank"/.test(m[0]) || !/rel="noopener"/.test(m[0])) fail(`play control for "${k}" must open a new tab (target="_blank" rel="noopener")`);
}
const local = (v) => typeof v === 'string' && !/^https?:/.test(v);
// Every in-page jump lands somewhere: data-go and data-scroll name an id that exists.
const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));
for (const m of html.matchAll(/\bdata-(go|scroll)="([^"]+)"/g)) if (!ids.has(m[2])) fail(`data-${m[1]}="${m[2]}" points at no element (no id="${m[2]}" in site/index.html)`);
const loopFiles = Object.values(media.loops).flatMap((v) => (v && typeof v === 'object' ? Object.values(v) : [v])).filter(local);
for (const f of loopFiles) if (!existsSync(P('site', f))) fail(`missing loop ${f}`);
// Case cover footage: per wing { av1, mp4 }, played full-bleed behind the case cover.
const covers = media.covers || {};
const coverFiles = Object.values(covers).flatMap((v) => Object.values(v || {})).filter(local);
for (const f of coverFiles) if (!existsSync(P('site', f))) fail(`missing cover footage ${f}`);
// The web build posts the brief to the Vercel Function in api/brief.mjs; the Artifact cannot reach it, so it keeps copy and mailto.
if (!existsSync(P('api/brief.mjs'))) fail('missing api/brief.mjs, the endpoint the web build posts the brief to');
const refsOf = (page) => [...new Set([...page.matchAll(/(?:src|poster)="(media\/[^"]+)"/g)].map((m) => m[1]))];
for (const r of refsOf(html)) if (!existsSync(P('site', r))) fail(`missing ${r}`);

// vercel.json caches /media/ for a year as immutable, so every media URL in dist/web carries its content's
// fingerprint: a file replaced in site/media/ under the same name gets a new URL, and no browser keeps the old one.
const stamp = (rel) => rel + '?v=' + createHash('sha256').update(readFileSync(P('site', rel))).digest('hex').slice(0, 10);
const webLoops = Object.fromEntries(Object.entries(media.loops).map(([k, v]) => [k, v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([t, f]) => [t, local(f) ? stamp(f) : f])) : local(v) ? stamp(v) : v]));
const webCovers = Object.fromEntries(Object.entries(covers).map(([k, v]) => [k, Object.fromEntries(Object.entries(v || {}).map(([t, f]) => [t, local(f) ? stamp(f) : f]))]));
// three.js r128 for the walk (#/explore), loaded by site/explore.js when the walk first opens. The web build serves the
// site's own copy, since its CSP allows scripts from 'self' only; the Artifact loads the same file from cdnjs, pinned
// to the copy's hash (cdnjs's r128 and npm's three@0.128.0 build are the same bytes).
const THREE_FILE = 'vendor/three.min.js';
if (!existsSync(P('site', THREE_FILE))) fail(`missing site/${THREE_FILE}, the three.js r128 build the walk loads`);
const THREE_CDN = 'https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js';
const THREE_SRI = 'sha512-' + createHash('sha512').update(readFileSync(P('site', THREE_FILE))).digest('base64');

// A web build: the source as files, tokens generated, manifest filled. CSP-friendly: no inline script.
// Returns how many images it carries.
function writeWeb(dir, page) {
  const out = withManifest(page, { loops: webLoops, covers: webCovers, films: media.films, embed: true, brief: '/api/brief', three: stamp(THREE_FILE) })
    .replace(/(src|poster)="(media\/[^"?]+)"/g, (_, attr, rel) => `${attr}="${stamp(rel)}"`);
  if (/"media\/[^"?]+"/.test(out)) fail(`a media URL in ${dir} has no content fingerprint (?v=)`);
  const own = refsOf(page);
  mkdirSync(P(dir, 'media'), { recursive: true });
  writeFileSync(P(dir, 'index.html'), out);
  for (const f of ['tokens.css', 'styles.css', 'boot.js', 'explore.js', 'main.js']) copyFileSync(P('site', f), P(dir, f));
  mkdirSync(P(dir, dirname(THREE_FILE)), { recursive: true });
  copyFileSync(P('site', THREE_FILE), P(dir, THREE_FILE));
  for (const r of [...own, ...loopFiles, ...coverFiles]) { mkdirSync(dirname(P(dir, r)), { recursive: true }); copyFileSync(P('site', r), P(dir, r)); }
  return own.length;
}
rmSync(P('dist'), { recursive: true, force: true });
const webImages = writeWeb('dist/web', webSource);
if (!shopLive) writeWeb('dist/preview', html);

// dist/artifact: a fragment (the Artifact skeleton supplies doctype, charset and viewport), everything inlined.
// Loops travel inside the page as data URIs, both formats of each (about 4.7 MB of the 16 MB limit). The cover footage
// travels as its H.264 copy only (about 4.4 MB more): the AV1 files would take the page past the limit. Films stay links,
// since an Artifact cannot embed YouTube.
const loopUri = (rel) => `data:video/${rel.endsWith('.webm') ? 'webm' : 'mp4'};base64,` + readFileSync(P('site', rel)).toString('base64');
const inline = (v) => (local(v) ? loopUri(v) : v);
const artLoops = Object.fromEntries(Object.entries(media.loops).map(([k, v]) => [k, v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([t, f]) => [t, inline(f)])) : inline(v)]));
// A film with an "asset" URL (uploaded to the Artifact's asset store) plays in the Artifact's own popup.
const artFilms = Object.fromEntries(Object.entries(media.films).map(([k, f]) => [k, f && f.asset ? { ...f, src: f.asset } : f]));
const artCovers = Object.fromEntries(Object.entries(covers).map(([k, v]) => [k, v && v.mp4 ? { mp4: inline(v.mp4) } : {}]));
html = withManifest(html, { loops: artLoops, covers: artCovers, films: artFilms, embed: false, three: THREE_CDN, threeIntegrity: THREE_SRI });
const scriptSafe = (s) => s.replace(/<\/script/gi, '<\\/script');
const dataUri = (rel) => 'data:image/jpeg;base64,' + readFileSync(P('site', rel)).toString('base64');
let head = html.slice(html.indexOf('<head>') + 6, html.indexOf('</head>'));
let body = html.slice(html.indexOf('<body>') + 6, html.lastIndexOf('</body>'));
head = head.replace(/<meta charset="[^"]*">\s*/, '').replace(/<meta name="viewport"[^>]*>\s*/, '');
head = once(head, /(<title>[^<]*<\/title>)/, (t) => t + '\n<meta name="claude:viewport-fit-sides" content="cover">');
head = once(head, /<link rel="stylesheet" href="tokens\.css">\s*<link rel="stylesheet" href="styles\.css">/, () => `<style>\n${read('site/tokens.css')}\n${read('site/styles.css')}</style>`);
head = once(head, /<script src="boot\.js"><\/script>/, () => `<script>${scriptSafe(read('site/boot.js'))}</script>`);
// Each still travels once. A photo the page shows more than once (the shop's sit on several cards and shelves) goes into
// one map, its images name it in data-pic, and a small script fills them in, templates included, before the page's own
// scripts run. A photo shown once is inlined where it stands.
const seen = new Map();
for (const [, rel] of body.matchAll(/ src="(media\/[^"]+\.jpg)"/g)) seen.set(rel, (seen.get(rel) || 0) + 1);
const shared = [...seen].filter(([, n]) => n > 1).map(([rel]) => rel);
body = body.replace(/ src="(media\/[^"]+\.jpg)"/g, (m, rel) => (shared.includes(rel) ? ` data-pic="${rel}"` : m));
body = body.replace(/(src|poster)="(media\/[^"]+\.jpg)"/g, (_, attr, rel) => `${attr}="${dataUri(rel)}"`);
const pics = shared.length ? `<script type="application/json" id="lf-pics">${JSON.stringify(Object.fromEntries(shared.map((rel) => [rel, dataUri(rel)])))}</script>\n`
  + `<script>(() => { const m = JSON.parse(document.getElementById('lf-pics').textContent), fill = (r) => r.querySelectorAll('img[data-pic]').forEach((i) => { i.src = m[i.dataset.pic]; }); fill(document); document.querySelectorAll('template').forEach((t) => fill(t.content)); })();</script>\n` : '';
body = once(body, /<script src="explore\.js"><\/script>/, () => `${pics}<script>\n${scriptSafe(read('site/explore.js'))}</script>`);
body = once(body, /<script src="main\.js"><\/script>/, () => `<script>\n${scriptSafe(read('site/main.js'))}</script>`);
const fragment = head.trim() + '\n' + body.trim() + '\n';
mkdirSync(P('dist/artifact'), { recursive: true });
writeFileSync(P('dist/artifact/lastfomo.html'), fragment);

/* ---------- 4. check what ships ---------- */
let ok = true;
if (!args.has('--no-check')) {
  ok = (await brandcheck({ html: P('dist/artifact/lastfomo.html') }, 'artifact')) && ok;
}
const kb = (p) => (statSync(P(p)).size / 1024).toFixed(0) + ' KB';
console.log(`build: dist/web/index.html ${kb('dist/web/index.html')} + ${webImages} images${shop ? (shopLive ? ', with the shop' : ', without the shop (site/shop.json: "live": false)') : ''}`);
if (shop && !shopLive) console.log(`build: dist/preview/index.html ${kb('dist/preview/index.html')}, the web build with the shop, for QA only`);
console.log(`build: dist/artifact/lastfomo.html ${kb('dist/artifact/lastfomo.html')}${shop ? ', with the shop' : ''}`);
const missing = Object.entries(media.loops).filter(([, v]) => !v).map(([w]) => w);
if (missing.length) console.log(`build: posters stand in for the ${missing.join(' and ')} loop${missing.length > 1 ? 's' : ''} (not uploaded yet)`);
const ledger = JSON.parse(read('brand/ledger.json'));
const ph = ledger.placeholders.filter((p) => fragment.includes(p.token)).map((p) => p.token);
if (ph.length) console.log(`build: placeholders still in the page: ${ph.join(', ')}`);
if (!ok) fail('brand check failed on the built artifact.');
